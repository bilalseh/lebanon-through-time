// Extracts simplified country outlines for the 3D map from Natural Earth
// (public domain) and writes them as a TypeScript module.
//
//   node scripts/extract-outline.mjs <ne_10m_admin_0_countries.geojson> src/data/lebanon/outline.ts
import { readFileSync, writeFileSync } from 'node:fs'

const [src, out] = process.argv.slice(2)
if (!src || !out) {
  console.error('usage: extract-outline.mjs <countries.geojson> <out.ts>')
  process.exit(1)
}

// Lebanon keeps fine detail; neighbours only need a rough land mask around it.
const COUNTRIES = { LBN: 0.003, SYR: 0.015, ISR: 0.015, PSX: 0.015 }
// lon/lat box the map covers, with margin: [minLon, minLat, maxLon, maxLat]
const BBOX = [33.9, 32.1, 37.9, 35.9]

const fc = JSON.parse(readFileSync(src, 'utf8'))

function outerRings(feature) {
  const g = feature.geometry
  if (g.type === 'Polygon') return [g.coordinates[0]]
  if (g.type === 'MultiPolygon') return g.coordinates.map((p) => p[0])
  return []
}

/** Sutherland-Hodgman clip of a ring against the bbox. */
function clip(ring) {
  const edges = [
    (p) => p[0] >= BBOX[0],
    (p) => p[1] >= BBOX[1],
    (p) => p[0] <= BBOX[2],
    (p) => p[1] <= BBOX[3],
  ]
  const intersect = (a, b, i) => {
    const axis = i % 2
    const bound = BBOX[i]
    const k = (bound - a[axis]) / (b[axis] - a[axis])
    return axis === 0 ? [bound, a[1] + k * (b[1] - a[1])] : [a[0] + k * (b[0] - a[0]), bound]
  }
  let poly = ring
  edges.forEach((inside, i) => {
    const next = []
    for (let j = 0; j < poly.length; j++) {
      const cur = poly[j]
      const prev = poly[(j + poly.length - 1) % poly.length]
      if (inside(cur)) {
        if (!inside(prev)) next.push(intersect(prev, cur, i))
        next.push(cur)
      } else if (inside(prev)) {
        next.push(intersect(prev, cur, i))
      }
    }
    poly = next
  })
  return poly
}

function perpDistance(p, a, b) {
  const dx = b[0] - a[0]
  const dy = b[1] - a[1]
  if (dx === 0 && dy === 0) return Math.hypot(p[0] - a[0], p[1] - a[1])
  const t = ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / (dx * dx + dy * dy)
  const k = Math.max(0, Math.min(1, t))
  return Math.hypot(p[0] - (a[0] + k * dx), p[1] - (a[1] + k * dy))
}

/** Douglas-Peucker line simplification. */
function simplify(points, tolerance) {
  if (points.length < 3) return points
  let maxDist = 0
  let index = 0
  const last = points.length - 1
  for (let i = 1; i < last; i++) {
    const d = perpDistance(points[i], points[0], points[last])
    if (d > maxDist) {
      maxDist = d
      index = i
    }
  }
  if (maxDist <= tolerance) return [points[0], points[last]]
  const left = simplify(points.slice(0, index + 1), tolerance)
  const right = simplify(points.slice(index), tolerance)
  return [...left.slice(0, -1), ...right]
}

const round = (ring) => ring.map(([x, y]) => [Number(x.toFixed(4)), Number(y.toFixed(4))])

const result = {}
for (const [code, tolerance] of Object.entries(COUNTRIES)) {
  const feature = fc.features.find((f) => f.properties.ADM0_A3 === code)
  if (!feature) {
    console.error(`country ${code} not found`)
    process.exit(1)
  }
  result[code] = outerRings(feature)
    .map(clip)
    .filter((r) => r.length >= 3)
    .map((r) => round(simplify(r, tolerance)))
    .filter((r) => r.length >= 3)
}

const fmt = (rings) => JSON.stringify(rings)
const ts = `/**
 * Simplified country outlines as [longitude, latitude] rings, generated by
 * scripts/extract-outline.mjs from Natural Earth 1:10m (public domain).
 * Neighbouring land is only a rough mask clipped to the map area; it is drawn
 * muted and unlabelled so Lebanon stands out.
 */
export type Ring = Array<[number, number]>

export const MAP_BBOX = { minLon: ${BBOX[0]}, minLat: ${BBOX[1]}, maxLon: ${BBOX[2]}, maxLat: ${BBOX[3]} }

export const LEBANON: Ring[] = ${fmt(result.LBN)}

export const NEIGHBOURS: Ring[] = ${fmt([...result.SYR, ...result.ISR, ...result.PSX])}
`
writeFileSync(out, ts)
console.log(
  Object.entries(result)
    .map(([k, v]) => `${k}: ${v.length} ring(s), ${v.reduce((n, r) => n + r.length, 0)} points`)
    .join('\n'),
)
